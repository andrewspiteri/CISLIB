using System.Text.Json;

namespace CIS.Configuration;

/// <summary>A logical store address. Adapters own physical escaping and consistency.</summary>
public sealed record ConfigurationRecordKey
{
    /// <summary>Creates an exact ordinal logical address; no physical path interpretation occurs here.</summary>
    public ConfigurationRecordKey(string scope, string definition)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(scope);
        ArgumentException.ThrowIfNullOrWhiteSpace(definition);
        Scope = scope;
        Definition = definition;
    }

    /// <summary>Gets the common or fixed host scope.</summary>
    public string Scope { get; }
    /// <summary>Gets the stable type/assembly definition generated by Configuration.</summary>
    public string Definition { get; }
}

/// <summary>Describes the store's notification guarantee; it does not select a transport.</summary>
public enum ConfigurationNotificationMode
{
    /// <summary>An external store requires actual Heartbeat polling with an explicit host interval.</summary>
    None,
    /// <summary>Usable watch/reconnect signals support reconciliation without periodic polling.</summary>
    Reliable,
    /// <summary>Watch signals need an explicit periodic reconciliation interval too.</summary>
    RequiresReconciliation
}

/// <summary>Distinguishes readable state, confirmed absence, conditional equality and failure.</summary>
public enum ConfigurationReadKind
{
    /// <summary>A complete detached object record.</summary>
    Found,
    /// <summary>The store successfully confirmed absence.</summary>
    Missing,
    /// <summary>The exact retained source state remains current.</summary>
    Unchanged,
    /// <summary>An unsuccessful read; never deletion.</summary>
    Failure
}

/// <summary>An immutable read result; factories detach JSON from provider-owned documents.</summary>
public sealed class ConfigurationReadResult
{
    private ConfigurationReadResult(ConfigurationReadKind kind, JsonElement? payload, string? sourceToken)
    { Kind = kind; Payload = payload; SourceToken = sourceToken; }

    /// <summary>Gets the read outcome.</summary>
    public ConfigurationReadKind Kind { get; }
    /// <summary>Gets the detached complete record when found.</summary>
    public JsonElement? Payload { get; }
    /// <summary>Gets an opaque equality token, not a globally ordered revision.</summary>
    public string? SourceToken { get; }

    /// <summary>Copies a complete record; mapping validates its shape later.</summary>
    public static ConfigurationReadResult Found(JsonElement payload, string? sourceToken = null)
        => new(ConfigurationReadKind.Found, payload.Clone(), sourceToken);
    /// <summary>Reports successful confirmed absence.</summary>
    public static ConfigurationReadResult Missing(string? sourceToken = null)
        => new(ConfigurationReadKind.Missing, null, sourceToken);
    /// <summary>Confirms the cached source state; invalid without an existing cache entry.</summary>
    public static ConfigurationReadResult Unchanged() => new(ConfigurationReadKind.Unchanged, null, null);
    /// <summary>Reports unsuccessful retrieval without retaining provider exceptions or secret payloads.</summary>
    public static ConfigurationReadResult Failure() => new(ConfigurationReadKind.Failure, null, null);
}

/// <summary>A key or scope invalidation/reconnect signal requesting a reread.</summary>
/// <remarks>A null Scope selects both owned scopes; a null Definition selects every discovered type within that selection.</remarks>
/// <param name="Scope">An exact scope or null for both owned scopes.</param>
/// <param name="Definition">An exact definition or null for every discovered type.</param>
public sealed record ConfigurationInvalidation(string? Scope = null, string? Definition = null);

/// <summary>Host-supplied bootstrap-capable storage. Configuration never disposes this adapter.</summary>
public interface IConfigurationStore
{
    /// <summary>Gets the adapter's documented watch/recovery guarantee.</summary>
    ConfigurationNotificationMode NotificationMode { get; }

    /// <summary>Reads one complete logical record, optionally conditioned on its last observed source token.</summary>
    ValueTask<ConfigurationReadResult> ReadAsync(ConfigurationRecordKey key, string? sourceToken, CancellationToken cancellationToken);

    /// <summary>Establishes observation; signal callbacks must be brief and nonblocking.</summary>
    /// <remarks>The returned owned subscription must detach on disposal. Reconnect signals require reconciliation.</remarks>
    ValueTask<IAsyncDisposable> WatchAsync(IReadOnlyList<ConfigurationRecordKey> keys,
        Action<ConfigurationInvalidation> invalidated, CancellationToken cancellationToken)
        => ValueTask.FromException<IAsyncDisposable>(new NotSupportedException("This provider does not support configuration watches."));
}
